package io.github.hugoneale.campat.tools;

import java.io.IOException;
import java.io.Writer;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.LinkedHashMap;
import java.util.Map;
import java.util.TreeMap;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * Generates the class rename table (every NeoForge class whose Forge counterpart exists under the
 * predictable name) and the NeoForge platform hierarchy index.
 *
 * <p>usage: MapGen neo_env.txt forge_env.txt outDir</p>
 */
public final class MapGen {
    private static final String[][] PREFIX = {
        {"net/neoforged/neoforge/", "net/minecraftforge/"},
        {"net/neoforged/fml/", "net/minecraftforge/fml/"},
        {"net/neoforged/bus/api/", "net/minecraftforge/eventbus/api/"},
        {"net/neoforged/neoforgespi/", "net/minecraftforge/forgespi/"},
        {"net/neoforged/api/distmarker/", "net/minecraftforge/api/distmarker/"},
    };
    private static final Map<String, String> SPECIAL = new LinkedHashMap<>();
    static {
        SPECIAL.put("net/neoforged/neoforge/common/NeoForge", "net/minecraftforge/common/MinecraftForge");
        SPECIAL.put("net/neoforged/neoforge/common/ModConfigSpec", "net/minecraftforge/common/ForgeConfigSpec");
        SPECIAL.put("net/neoforged/neoforge/common/ItemAbility", "net/minecraftforge/common/ToolAction");
        SPECIAL.put("net/neoforged/neoforge/common/ItemAbilities", "net/minecraftforge/common/ToolActions");
        SPECIAL.put("net/neoforged/neoforge/common/CommonHooks", "net/minecraftforge/common/ForgeHooks");
        SPECIAL.put("net/neoforged/neoforge/client/ClientHooks", "net/minecraftforge/client/ForgeHooksClient");
        SPECIAL.put("net/neoforged/neoforge/event/EventHooks", "net/minecraftforge/event/ForgeEventFactory");
        SPECIAL.put("net/neoforged/neoforge/common/NeoForgeMod", "net/minecraftforge/common/ForgeMod");
        SPECIAL.put("net/neoforged/neoforge/common/NeoForgeConfig", "net/minecraftforge/common/ForgeConfig");
        SPECIAL.put("net/neoforged/neoforge/registries/NeoForgeRegistries", "net/minecraftforge/registries/ForgeRegistries");
        SPECIAL.put("net/neoforged/neoforge/common/conditions/ICondition", "net/minecraftforge/common/crafting/conditions/ICondition");
        SPECIAL.put("net/neoforged/neoforge/common/conditions/IConditionBuilder", "net/minecraftforge/common/crafting/conditions/IConditionBuilder");
    }

    public static void main(String[] args) throws IOException {
        PlatformEnv neo = PlatformEnv.fromList(Path.of(args[0]));
        PlatformEnv forge = PlatformEnv.fromList(Path.of(args[1]));
        Path out = Path.of(args[2]);
        Files.createDirectories(out.resolve("mappings"));

        Map<String, String> renames = new TreeMap<>();
        for (String c : neo.classes.keySet()) {
            if (!c.startsWith("net/neoforged/")) continue;
            String t = candidate(c);
            if (t != null && forge.get(t) != null) renames.put(c, t);
        }
        try (Writer w = Files.newBufferedWriter(out.resolve("mappings/classes.txt"))) {
            w.write("# GENERATED by :tools:genMappings - NeoForge classes with a same-shaped Forge counterpart.\n");
            w.write("# Classes the runtime provides under their NeoForge name are excluded at load time.\n");
            for (var e : renames.entrySet()) w.write("C " + e.getKey() + " " + e.getValue() + "\n");
        }
        int n = 0;
        try (Writer w = Files.newBufferedWriter(out.resolve("hierarchy.txt"))) {
            for (var c : new TreeMap<>(neo.classes).values()) {
                String name = c.name();
                if (!(name.startsWith("net/neoforged/") || name.startsWith("net/minecraft/") || name.startsWith("com/mojang/"))) continue;
                StringBuilder sb = new StringBuilder(name).append(' ').append(c.superName() == null ? "-" : c.superName());
                for (String i : c.interfaces()) sb.append(' ').append(i);
                w.write(sb.append('\n').toString());
                n++;
            }
        }
        System.out.println(renames.size() + " class renames, " + n + " hierarchy entries");
    }

    static String candidate(String c) {
        String outer = c, inner = "";
        int d = c.indexOf('$');
        if (d >= 0) { outer = c.substring(0, d); inner = c.substring(d); }
        if (SPECIAL.containsKey(outer)) return SPECIAL.get(outer) + inner;
        for (String[] p : PREFIX) {
            if (outer.startsWith(p[0])) {
                String rest = outer.substring(p[0].length());
                String simple = rest.substring(rest.lastIndexOf('/') + 1);
                String pkg = rest.substring(0, rest.lastIndexOf('/') + 1);
                Matcher m = Pattern.compile("^I(\\w+)Extension$").matcher(simple);
                if (pkg.endsWith("extensions/") && m.matches()) simple = "IForge" + m.group(1);
                simple = simple.replace("NeoForge", "Forge");
                return p[1] + pkg + simple + inner;
            }
        }
        return null;
    }
}
